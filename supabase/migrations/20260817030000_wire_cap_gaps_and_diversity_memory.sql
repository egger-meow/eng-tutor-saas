-- 2. Enhanced worker_generation_context with Direct Gap Recommendations and Item Family Diversity
create or replace function public.worker_generation_context(job_id uuid, worker_id text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed_job public.generation_jobs;
  child_rec record;
  result jsonb;
  v_vocab_due jsonb;
  v_vocab_weak jsonb;
  v_vocab_uncertain jsonb;
  v_vocab_mastered jsonb;
  v_vocab_count integer;
  v_grammar_due jsonb;
  v_grammar_weak jsonb;
  v_grammar_uncertain jsonb;
  v_grammar_mastered jsonb;
  v_grammar_count integer;
  v_comm_due jsonb;
  v_comm_weak jsonb;
  v_comm_mastered jsonb;
  v_comm_count integer;
  v_vocab_exp_count integer;
  v_vocab_mastered_count integer;
  v_vocab_due_count integer;
  v_grammar_exp_count integer;
  v_grammar_mastered_count integer;
  v_grammar_due_count integer;
  v_comm_exp_count integer;
  v_comm_mastered_count integer;
  v_comm_due_count integer;
  v_rec_vocab jsonb;
  v_rec_grammar jsonb;
  v_rec_comm jsonb;
  v_recent_genres jsonb;
  v_recent_contexts jsonb;
  v_recent_families jsonb;
begin
  select * into claimed_job
  from public.generation_jobs as job
  where job.id = $1
    and job.status = 'claimed'
    and job.claimed_by = $2
    and job.lease_expires_at > now();

  if claimed_job.id is null then
    raise exception 'job is not actively claimed by this worker';
  end if;

  select child.*, profile.interests as profile_interests
  into child_rec
  from public.children as child
  left join public.child_profiles as profile on profile.child_id = child.id
  where child.id = claimed_job.child_id;

  -- Distill vocabulary into decision categories
  select
    coalesce(jsonb_agg(vocabulary_id) filter (where status = 'reviewing' or (last_seen_at < now() - interval '6 days' and status != 'mastered')), '[]'::jsonb),
    coalesce(jsonb_agg(vocabulary_id) filter (where (mastery_score is not null and mastery_score < 60) or (exposure_count > 1 and correct_count < exposure_count / 2)), '[]'::jsonb),
    coalesce(jsonb_agg(vocabulary_id) filter (where status = 'new' or (exposure_count = 1 and correct_count = 0)), '[]'::jsonb),
    coalesce(jsonb_agg(vocabulary_id) filter (where status = 'mastered'), '[]'::jsonb),
    count(*)
  into v_vocab_due, v_vocab_weak, v_vocab_uncertain, v_vocab_mastered, v_vocab_count
  from public.child_vocab_progress
  where child_id = claimed_job.child_id;

  -- Distill grammar into decision categories
  select
    coalesce(jsonb_agg(grammar_id) filter (where status = 'reviewing' or (last_seen_at < now() - interval '6 days' and status != 'mastered')), '[]'::jsonb),
    coalesce(jsonb_agg(grammar_id) filter (where (mastery_score is not null and mastery_score < 60) or (exposure_count > 1 and correct_count < exposure_count / 2)), '[]'::jsonb),
    coalesce(jsonb_agg(grammar_id) filter (where status in ('new', 'learning')), '[]'::jsonb),
    coalesce(jsonb_agg(grammar_id) filter (where status = 'mastered'), '[]'::jsonb),
    count(*)
  into v_grammar_due, v_grammar_weak, v_grammar_uncertain, v_grammar_mastered, v_grammar_count
  from public.child_grammar_progress
  where child_id = claimed_job.child_id;

  -- Distill communication functions into decision categories
  select
    coalesce(jsonb_agg(communication_function_id) filter (where status = 'reviewing' or (last_seen_at < now() - interval '14 days' and status != 'mastered')), '[]'::jsonb),
    coalesce(jsonb_agg(communication_function_id) filter (where (exposure_count > 1 and miss_count > 0) or status = 'learning'), '[]'::jsonb),
    coalesce(jsonb_agg(communication_function_id) filter (where status = 'mastered'), '[]'::jsonb),
    count(*)
  into v_comm_due, v_comm_weak, v_comm_mastered, v_comm_count
  from public.child_communication_progress
  where child_id = claimed_job.child_id;

  -- Factual counts
  v_vocab_exp_count := coalesce(v_vocab_count, 0);
  v_vocab_mastered_count := jsonb_array_length(coalesce(v_vocab_mastered, '[]'::jsonb));
  v_vocab_due_count := jsonb_array_length(coalesce(v_vocab_due, '[]'::jsonb));

  v_grammar_exp_count := coalesce(v_grammar_count, 0);
  v_grammar_mastered_count := jsonb_array_length(coalesce(v_grammar_mastered, '[]'::jsonb));
  v_grammar_due_count := jsonb_array_length(coalesce(v_grammar_due, '[]'::jsonb));

  v_comm_exp_count := coalesce(v_comm_count, 0);
  v_comm_mastered_count := jsonb_array_length(coalesce(v_comm_mastered, '[]'::jsonb));
  v_comm_due_count := jsonb_array_length(coalesce(v_comm_due, '[]'::jsonb));

  -- 1. Recommended Vocabulary Gap Fill (Up to 8 canonical unexposed/due items for grade stage)
  select coalesce(jsonb_agg(sub.id), '[]'::jsonb)
  into v_rec_vocab
  from (
    select ccv.id
    from public.canonical_curriculum_vocabulary as ccv
    left join public.child_vocab_progress as cvp
      on cvp.child_id = claimed_job.child_id and cvp.vocabulary_id = ccv.id
    where (cvp.vocabulary_id is null or cvp.status in ('learning', 'reviewing'))
      and (child_rec.grade_stage is null or ccv.grade_stage <= child_rec.grade_stage)
    order by (cvp.vocabulary_id is not null) desc, ccv.id asc
    limit 8
  ) as sub;

  -- 2. Recommended Grammar Gap Fill (Up to 2 canonical units for grade stage)
  select coalesce(jsonb_agg(sub.unit_id), '[]'::jsonb)
  into v_rec_grammar
  from (
    select cgu.unit_id
    from public.canonical_grammar_units as cgu
    left join public.child_grammar_progress as cgp
      on cgp.child_id = claimed_job.child_id and cgp.grammar_id = cgu.unit_id
    where (cgp.grammar_id is null or cgp.status in ('learning', 'reviewing'))
      and (child_rec.grade_stage is null or cgu.grade_stage <= child_rec.grade_stage)
    order by (cgp.grammar_id is not null) desc, cgu.unit_id asc
    limit 2
  ) as sub;

  -- 3. Recommended Communication Function Gap Fill (Up to 2 canonical functions)
  select coalesce(jsonb_agg(sub.id), '[]'::jsonb)
  into v_rec_comm
  from (
    select ccf.id
    from public.canonical_communication_functions as ccf
    left join public.child_communication_progress as ccp
      on ccp.child_id = claimed_job.child_id and ccp.communication_function_id = ccf.id
    where (ccp.communication_function_id is null or ccp.status in ('learning', 'reviewing'))
    order by (ccp.communication_function_id is not null) desc, ccf.id asc
    limit 2
  ) as sub;

  -- 4. Diversity Capsule: Recent genres, scenario context keys, and question item families (last 2-4 weeks)
  select coalesce(jsonb_agg(distinct g.genre), '[]'::jsonb)
  into v_recent_genres
  from (
    select coalesce(m.canonical_source #>> '{studentLesson,reading,genre}', 'article') as genre
    from public.materials as m
    where m.child_id = claimed_job.child_id
    order by m.material_week desc
    limit 4
  ) as g where g.genre is not null;

  select coalesce(jsonb_agg(distinct k.context_key), '[]'::jsonb)
  into v_recent_contexts
  from (
    select coalesce(
      m.canonical_source #>> '{studentLesson,reading,contextKey}',
      m.canonical_source #>> '{studentLesson,reading,title}',
      m.generation_summary ->> 'theme'
    ) as context_key
    from public.materials as m
    where m.child_id = claimed_job.child_id
    order by m.material_week desc
    limit 4
  ) as k where k.context_key is not null;

  select coalesce(jsonb_agg(distinct it.item_type), '[]'::jsonb)
  into v_recent_families
  from (
    select question ->> 'itemType' as item_type
    from (
      select m.canonical_source
      from public.materials as m
      where m.child_id = claimed_job.child_id
      order by m.material_week desc
      limit 4
    ) as recent_m
    cross join lateral (
      select jsonb_array_elements(stage -> 'questions') as question
      from jsonb_array_elements(coalesce(recent_m.canonical_source #> '{studentLesson,practice}', '[]'::jsonb)) as stage
      union all
      select jsonb_array_elements(coalesce(recent_m.canonical_source #> '{studentLesson,homework,questions}', '[]'::jsonb))
    ) as q
  ) as it where it.item_type is not null;

  select jsonb_build_object(
    'job', jsonb_build_object(
      'id', claimed_job.id, 'childId', claimed_job.child_id,
      'materialWeek', claimed_job.material_week, 'ruleVersion', claimed_job.rule_version,
      'releaseAt', claimed_job.release_at, 'feedbackCutoffAt', claimed_job.feedback_cutoff_at,
      'feedbackMissing', claimed_job.feedback_missing, 'sourceMaterialId', claimed_job.source_material_id
    ),
    'child', jsonb_build_object(
      'grade', child_rec.grade, 'gradeStage', child_rec.grade_stage,
      'textbookVersion', child_rec.textbook_version, 'preferences', child_rec.preferences
    ),
    'profile', to_jsonb(profile) - 'child_id' - 'created_at' - 'updated_at',
    'learningState', to_jsonb(state) - 'child_id' - 'updated_at',
    'vocabularyCapsule', jsonb_build_object(
      'dueForReview', v_vocab_due,
      'weakRecent', v_vocab_weak,
      'uncertain', v_vocab_uncertain,
      'recentlyMastered', v_vocab_mastered,
      'historicalCount', v_vocab_exp_count
    ),
    'grammarCapsule', jsonb_build_object(
      'dueForReview', v_grammar_due,
      'weakRecent', v_grammar_weak,
      'uncertain', v_grammar_uncertain,
      'recentlyMastered', v_grammar_mastered,
      'historicalCount', v_grammar_exp_count
    ),
    'communicationCapsule', jsonb_build_object(
      'dueForReview', v_comm_due,
      'weakRecent', v_comm_weak,
      'recentlyMastered', v_comm_mastered,
      'historicalCount', v_comm_exp_count
    ),
    'capCoverageCapsule', jsonb_build_object(
      'dueReviewVocabulary', v_vocab_due,
      'dueReviewGrammar', v_grammar_due,
      'dueReviewCommunication', v_comm_due,
      'recommendedVocabulary', v_rec_vocab,
      'recommendedGrammar', v_rec_grammar,
      'recommendedCommunicationFunctions', v_rec_comm,
      'coverage', jsonb_build_object(
        'vocabulary', jsonb_build_object(
          'totalUniverse', 2000,
          'exposedCount', v_vocab_exp_count,
          'masteredCount', v_vocab_mastered_count,
          'dueReviewCount', v_vocab_due_count,
          'exposurePct', round((v_vocab_exp_count::numeric / 2000.0) * 100.0, 1),
          'masteryPct', round((v_vocab_mastered_count::numeric / 2000.0) * 100.0, 1)
        ),
        'grammar', jsonb_build_object(
          'totalUniverse', 24,
          'exposedCount', v_grammar_exp_count,
          'masteredCount', v_grammar_mastered_count,
          'dueReviewCount', v_grammar_due_count,
          'exposurePct', round((v_grammar_exp_count::numeric / 24.0) * 100.0, 1),
          'masteryPct', round((v_grammar_mastered_count::numeric / 24.0) * 100.0, 1)
        ),
        'communication', jsonb_build_object(
          'totalUniverse', 16,
          'exposedCount', v_comm_exp_count,
          'masteredCount', v_comm_mastered_count,
          'dueReviewCount', v_comm_due_count,
          'exposurePct', round((v_comm_exp_count::numeric / 16.0) * 100.0, 1),
          'masteryPct', round((v_comm_mastered_count::numeric / 16.0) * 100.0, 1)
        )
      )
    ),
    'diversityCapsule', jsonb_build_object(
      'recentGenres', v_recent_genres,
      'recentContextKeys', v_recent_contexts,
      'recentItemFamilies', v_recent_families
    ),
    'sourceMaterial', case when source_material.id is null then null else jsonb_build_object(
      'id', source_material.id, 'materialWeek', source_material.material_week,
      'generationSummary', source_material.generation_summary
    ) end,
    'feedback', case when feedback.id is null then null else to_jsonb(feedback) - 'child_id' - 'updated_at' end
  ) into result
  from public.children as child
  join public.child_profiles as profile on profile.child_id = child.id
  join public.child_learning_state as state on state.child_id = child.id
  left join public.materials as source_material on source_material.id = claimed_job.source_material_id
  left join public.feedback as feedback
    on feedback.child_id = claimed_job.child_id
    and feedback.material_id = claimed_job.source_material_id
    and feedback.created_at <= claimed_job.feedback_cutoff_at
  where child.id = claimed_job.child_id;

  return result;
end;
$$;

-- 3. Enhanced worker_record_curriculum_observations with Strict Fail-Closed Canonical Persistence
create or replace function public.worker_record_curriculum_observations(
  material_id uuid,
  worker_id text,
  canonical_source jsonb
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  material_row public.materials;
  source jsonb;
  child_id_value uuid;
  vocabulary_item jsonb;
  raw_word text;
  raw_id text;
  canonical_vocab_id text;
  grammar_target_id text;
  comm_func_id text;
  quality_item jsonb;
  history_entry jsonb;
  target_evidence jsonb;
begin
  perform $3;
  select material.* into material_row
  from public.materials as material
  join public.generation_jobs as job on job.material_id = material.id
  where material.id = $1
    and job.status = 'completed'
    and job.claimed_by = $2
  for update of material;

  if material_row.id is null then raise exception 'completed material is not owned by this worker'; end if;
  if material_row.observations_recorded_at is not null then return false; end if;

  source := material_row.canonical_source;
  child_id_value := material_row.child_id;

  -- 1. Vocabulary exposure recording (Strict Fail-Closed: Only canonical 2000 vocabulary enters child_vocab_progress)
  for vocabulary_item in
    select value from jsonb_array_elements(coalesce(source #> '{studentLesson,vocabulary}', '[]'::jsonb))
  loop
    raw_word := lower(trim(coalesce(vocabulary_item->>'word', '')));
    raw_id := trim(coalesce(vocabulary_item->>'id', ''));

    select ccv.id into canonical_vocab_id
    from public.canonical_curriculum_vocabulary as ccv
    where ccv.id = raw_id or ccv.word = raw_word or ccv.id = 'v-' || raw_word
    limit 1;

    if canonical_vocab_id is not null then
      insert into public.child_vocab_progress (
        child_id, vocabulary_id, status, exposure_count, last_seen_at, last_material_id
      ) values (
        child_id_value,
        canonical_vocab_id,
        case vocabulary_item->>'status'
          when 'repeated-miss' then 'learning'
          when 'review' then 'reviewing'
          else 'new'
        end,
        1, now(), $1
      )
      on conflict (child_id, vocabulary_id) do update
      set exposure_count = public.child_vocab_progress.exposure_count + 1,
          last_seen_at = now(),
          last_material_id = excluded.last_material_id,
          status = case when public.child_vocab_progress.status = 'mastered' then 'mastered' else excluded.status end,
          updated_at = now();
    end if;
    -- Non-canonical domain words (Minecraft, redstone, sensor) are skipped to avoid polluting 2000 denominator
  end loop;

  -- 2. Grammar target exposure recording (Strict Fail-Closed: Only 24 canonical derived units)
  for grammar_target_id in
    select jsonb_array_elements_text(coalesce(source #> '{trackingDelta,exposedGrammarTargetIds}', '[]'::jsonb))
  loop
    if grammar_target_id is not null and exists (select 1 from public.canonical_grammar_units where unit_id = grammar_target_id) then
      insert into public.child_grammar_progress (
        child_id, grammar_id, status, exposure_count, last_seen_at, last_material_id
      ) values (child_id_value, left(grammar_target_id, 160), 'learning', 1, now(), $1)
      on conflict (child_id, grammar_id) do update
      set exposure_count = public.child_grammar_progress.exposure_count + 1,
          last_seen_at = now(),
          last_material_id = excluded.last_material_id,
          updated_at = now();
    end if;
  end loop;

  -- 3. Communication function exposure recording (Strict Fail-Closed: Only 16 official functions)
  for comm_func_id in
    select jsonb_array_elements_text(coalesce(source #> '{trackingDelta,exposedCommunicationFunctionIds}', '[]'::jsonb))
  loop
    if comm_func_id is not null and exists (select 1 from public.canonical_communication_functions where id = comm_func_id) then
      insert into public.child_communication_progress (
        child_id, communication_function_id, status, exposure_count, last_seen_at, last_material_id
      ) values (
        child_id_value, left(comm_func_id, 160), 'learning', 1, now(), $1
      )
      on conflict (child_id, communication_function_id) do update
      set exposure_count = public.child_communication_progress.exposure_count + 1,
          last_seen_at = now(),
          last_material_id = excluded.last_material_id,
          updated_at = now();
    end if;
  end loop;

  -- 4. Target Evidence Aggregation
  select coalesce(jsonb_agg(jsonb_build_object(
    'targetId', evidence.target_id,
    'checks', evidence.checks
  ) order by evidence.target_id), '[]'::jsonb)
  into target_evidence
  from (
    select item.target_id,
           jsonb_agg(jsonb_build_object('questionId', item.question_id, 'stage', item.stage)
             order by item.stage, item.question_id) as checks
    from (
      select target.value as target_id, question->>'id' as question_id, stage->>'stage' as stage
      from jsonb_array_elements(coalesce(source #> '{studentLesson,practice}', '[]'::jsonb)) as stage
      cross join lateral jsonb_array_elements(coalesce(stage->'questions', '[]'::jsonb)) as question
      cross join lateral jsonb_array_elements_text(coalesce(question->'targetIds', '[]'::jsonb)) as target(value)
      union all
      select target.value, question->>'id', 'homework'
      from jsonb_array_elements(coalesce(source #> '{studentLesson,homework,questions}', '[]'::jsonb)) as question
      cross join lateral jsonb_array_elements_text(coalesce(question->'targetIds', '[]'::jsonb)) as target(value)
    ) as item
    group by item.target_id
  ) as evidence;

  -- 5. Quality Findings & Observations
  for quality_item in
    select value from jsonb_array_elements(coalesce(source #> '{qualityEvidence,criticalChecks}', '[]'::jsonb))
  loop
    insert into public.curriculum_quality_observations (
      child_id, material_id, dimension, passed, severity, finding, resolution
    ) values (
      child_id_value, $1,
      coalesce(quality_item->>'id', 'general'),
      coalesce((quality_item->>'passed')::boolean, true),
      'info',
      coalesce(quality_item->>'evidence', 'Check passed'),
      'passed'
    );
  end loop;

  for quality_item in
    select value from jsonb_array_elements(coalesce(source #> '{qualityEvidence,criticFindings}', '[]'::jsonb))
  loop
    insert into public.curriculum_quality_observations (
      child_id, material_id, dimension, passed, severity, finding, resolution
    ) values (
      child_id_value, $1,
      coalesce(quality_item->>'dimension', 'general'),
      false,
      coalesce(quality_item->>'severity', 'critical'),
      coalesce(quality_item->>'finding', 'Finding recorded'),
      quality_item->>'resolution'
    );
  end loop;

  -- 6. Update Child Learning State with Target Evidence and Progress History
  history_entry := jsonb_build_object(
    'materialId', $1,
    'materialWeek', material_row.material_week,
    'recordedAt', now(),
    'wordCount', coalesce((source #> '{studentLesson,reading,wordCount}')::integer, 0),
    'introducedVocabularyCount', jsonb_array_length(coalesce(source #> '{trackingDelta,introducedVocabularyIds}', '[]'::jsonb)),
    'reviewedVocabularyCount', jsonb_array_length(coalesce(source #> '{trackingDelta,reviewedVocabularyIds}', '[]'::jsonb)),
    'exposedGrammarCount', jsonb_array_length(coalesce(source #> '{trackingDelta,exposedGrammarTargetIds}', '[]'::jsonb)),
    'exposedReadingCount', jsonb_array_length(coalesce(source #> '{trackingDelta,exposedReadingTargetIds}', '[]'::jsonb)),
    'exposedCommunicationCount', jsonb_array_length(coalesce(source #> '{trackingDelta,exposedCommunicationFunctionIds}', '[]'::jsonb)),
    'hypotheses', coalesce(source #> '{trackingDelta,hypothesesToVerify}', '[]'::jsonb),
    'targetEvidence', coalesce(target_evidence, '[]'::jsonb)
  );

  update public.child_learning_state
  set current_difficulty_band = coalesce(source #>> '{learningPlan,difficultyBand}', current_difficulty_band),
      last_material_id = $1,
      last_material_week = material_row.material_week,
      progress_history = case
        when jsonb_typeof(progress_history) = 'array' then
          jsonb_build_array(history_entry) || (
            select coalesce(jsonb_agg(value), '[]'::jsonb)
            from (
              select value from jsonb_array_elements(progress_history) limit 11
            ) as recent_history
          )
        else jsonb_build_array(history_entry)
      end,
      updated_at = now()
  where child_id = child_id_value;

  update public.materials
  set observations_recorded_at = now(),
      updated_at = now()
  where id = $1;

  return true;
end;
